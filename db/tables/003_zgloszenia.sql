create table zgloszenia (
    id              number generated by default on null as identity
                    constraint zgloszenia_pk primary key,
    numer           varchar2(20 char)
                    generated always as ('DF-' || lpad(to_char(id), 5, '0')) virtual,
    tytul           varchar2(200 char)  not null,
    opis            varchar2(4000 char),
    kategoria_id    number not null
                    constraint zgloszenia_kategoria_fk references kategorie (id),
    zglaszajacy_id  number not null
                    constraint zgloszenia_zglaszajacy_fk references uzytkownicy (id),
    przypisany_id   number
                    constraint zgloszenia_przypisany_fk references uzytkownicy (id),
    status          varchar2(20 char) default 'NOWE' not null
                    constraint zgloszenia_status_ck
                    check (status in ('NOWE', 'W_TOKU', 'OCZEKUJE', 'ROZWIAZANE', 'ZAMKNIETE')),
    utworzono       date default sysdate not null,
    zaktualizowano  date,
    rozwiazano      date
);

create index zgloszenia_kategoria_ix   on zgloszenia (kategoria_id);
create index zgloszenia_zglaszajacy_ix on zgloszenia (zglaszajacy_id);
create index zgloszenia_przypisany_ix  on zgloszenia (przypisany_id);
create index zgloszenia_status_ix      on zgloszenia (status);

