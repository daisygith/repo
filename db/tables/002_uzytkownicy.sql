--comment: Użytkownicy aplikacji i ich role
create table uzytkownicy (
    id                 number generated by default on null as identity
                       constraint uzytkownicy_pk primary key,
    login              varchar2(50 char)  not null
                       constraint uzytkownicy_login_uk unique,
    nazwa_wyswietlana  varchar2(100 char) not null,
    rola               varchar2(20 char)  not null
                       constraint uzytkownicy_rola_ck
                       check (rola in ('ZGLASZAJACY', 'ODBIERAJACY_SD', 'ADMIN')),
    aktywny            varchar2(1 char)   default 'T' not null
                       constraint uzytkownicy_aktywny_ck check (aktywny in ('T', 'N'))
);

comment on table  uzytkownicy      is 'Użytkownicy aplikacji DeskFlow';
comment on column uzytkownicy.rola is 'ZGLASZAJACY = zgłasza problemy, ODBIERAJACY_SD = pracownik service desku, ADMIN = kierownik service desku';
